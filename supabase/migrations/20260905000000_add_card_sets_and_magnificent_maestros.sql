create table public.card_sets (
  id bigint generated by default as identity primary key,
  tcg_slug text not null,
  slug text not null unique,
  name text not null,
  status text not null default 'draft' check (status in ('draft', 'live', 'archived')),
  release_date date,
  serials_per_card integer not null default 200 check (serials_per_card > 0),
  created_at timestamptz not null default now()
);

alter table public.card_sets enable row level security;

revoke all on table public.card_sets from anon, authenticated;
grant select on table public.card_sets to anon, authenticated;

create policy "Public can view live card sets"
on public.card_sets for select to anon
using (status = 'live');

create policy "Admins can view all card sets"
on public.card_sets for select to authenticated
using (
  status = 'live'
  or (
    (select auth.jwt() ->> 'aal') = 'aal2'
    and exists (
      select 1 from public.admins
      where admins.user_id = (select auth.uid())
    )
  )
);

