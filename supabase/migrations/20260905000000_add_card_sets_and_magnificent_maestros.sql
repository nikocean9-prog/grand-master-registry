with new_serials as (
  select cards.id as card_id,
         numbers.serial_number,
         regions.region,
         row_number() over (order by cards.id, regions.region, numbers.serial_number) as position
  from public.cards
  join public.card_sets on card_sets.id = cards.set_id
  cross join generate_series(1, 100) as numbers(serial_number)
  cross join (values ('AMERICAS'::text), ('E'::text)) as regions(region)
  where card_sets.slug = 'magnificent-maestros'
), next_serial_id as (
  select coalesce(max(id), 0) as value from public.serials
)
insert into public.serials (id, card_id, serial_number, region, status)
select next_serial_id.value + new_serials.position,
       new_serials.card_id,
       new_serials.serial_number,
       new_serials.region,
       'unreported'
from new_serials
cross join next_serial_id;

